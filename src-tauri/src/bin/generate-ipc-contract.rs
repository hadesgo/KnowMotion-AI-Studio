use knowmotion_ai_studio_lib::ipc_contract::contract_schema;
use serde_json::{Map, Value};
use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

fn main() {
    if let Err(error) = run() {
        eprintln!("IPC contract generation failed: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let repository = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or_else(|| "Repository root is unavailable".to_string())?
        .to_path_buf();
    let typescript_path = repository.join("src/generated/ipc.ts");
    let schema_path = repository.join("docs/schemas/ipc.schema.json");

    let mut schema = contract_schema();
    let object = schema
        .as_object_mut()
        .ok_or_else(|| "IPC root schema is not an object".to_string())?;
    object.insert(
        "$id".to_string(),
        Value::String("https://knowmotion.local/schemas/ipc.schema.json".to_string()),
    );
    object.insert(
        "title".to_string(),
        Value::String("KnowMotion IPC Contract".to_string()),
    );
    let typescript = render_typescript(&schema)?;
    let schema_text = format!(
        "{}\n",
        serde_json::to_string_pretty(&schema).map_err(|error| error.to_string())?
    );

    let check = std::env::args().any(|argument| argument == "--check");
    if check {
        check_current(&typescript_path, &typescript, "src/generated/ipc.ts")?;
        check_current(&schema_path, &schema_text, "docs/schemas/ipc.schema.json")?;
        println!("IPC TypeScript and JSON Schema are current.");
        return Ok(());
    }

    write_generated(&typescript_path, &typescript)?;
    write_generated(&schema_path, &schema_text)?;
    println!(
        "Generated {} and {}",
        typescript_path.display(),
        schema_path.display()
    );
    Ok(())
}

fn write_generated(path: &Path, contents: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|error| error.to_string())?;
    }
    fs::write(path, contents)
        .map_err(|error| format!("Unable to write {}: {error}", path.display()))
}

fn check_current(path: &Path, expected: &str, label: &str) -> Result<(), String> {
    let actual = fs::read_to_string(path)
        .map_err(|error| format!("{label} is missing or unreadable: {error}"))?;
    if normalize_line_endings(&actual) != normalize_line_endings(expected) {
        return Err(format!(
            "{label} is stale; run `npm run ipc:generate` and commit the result"
        ));
    }
    Ok(())
}

/// The generator always writes LF, but a Windows checkout with
/// `core.autocrlf=true` turns the committed files into CRLF on disk. Comparing
/// raw bytes would then report a bogus "stale" result and break the gate on
/// every clean checkout, so compare after normalising line endings.
fn normalize_line_endings(text: &str) -> String {
    text.replace("\r\n", "\n")
}

fn render_typescript(root: &Value) -> Result<String, String> {
    let mut definitions = BTreeMap::new();
    if let Some(schema_definitions) = root.get("definitions").and_then(Value::as_object) {
        for (name, schema) in schema_definitions {
            definitions.insert(name.clone(), schema);
        }
    }

    let mut output = String::from(
        "// Generated by `npm run ipc:generate` from Rust runtime DTOs.\n\
         // Do not edit this file by hand.\n\n",
    );
    for (name, schema) in &definitions {
        output.push_str(&render_declaration(name, schema, &definitions, 0)?);
        output.push_str("\n\n");
    }

    // `IpcTypes` is the root when Schemars keeps it inline rather than in definitions.
    if !definitions.contains_key("IpcTypes") {
        output.push_str(&render_declaration("IpcTypes", root, &definitions, 0)?);
        output.push('\n');
    }
    Ok(output)
}

fn render_declaration(
    name: &str,
    schema: &Value,
    definitions: &BTreeMap<String, &Value>,
    indent: usize,
) -> Result<String, String> {
    let docs = doc_comment(schema, indent);
    if let Some(object) = schema.as_object() {
        if object.get("type").and_then(Value::as_str) == Some("object")
            || object.contains_key("properties")
        {
            let required = required_fields(schema);
            let mut output = docs;
            output.push_str(&format!("{}export interface {name} {{\n", spaces(indent)));
            if let Some(properties) = object.get("properties").and_then(Value::as_object) {
                for (property, property_schema) in properties {
                    output.push_str(&doc_comment(property_schema, indent + 2));
                    let optional = if required.contains(property) { "" } else { "?" };
                    let expression = type_expression(property_schema, definitions, indent + 2)?;
                    output.push_str(&format!(
                        "{}  {property}{optional}: {expression};\n",
                        spaces(indent)
                    ));
                }
            }
            if object.get("additionalProperties").and_then(Value::as_bool) == Some(true) {
                output.push_str(&format!("{}  [key: string]: unknown;\n", spaces(indent)));
            }
            output.push_str(&format!("{}}}\n", spaces(indent)));
            return Ok(output);
        }
    }
    Ok(format!(
        "{}export type {name} = {};\n",
        spaces(indent),
        type_expression(schema, definitions, indent)?
    ))
}

fn required_fields(schema: &Value) -> Vec<String> {
    schema
        .get("required")
        .and_then(Value::as_array)
        .map(|values| {
            values
                .iter()
                .filter_map(Value::as_str)
                .map(str::to_string)
                .collect()
        })
        .unwrap_or_default()
}

fn type_expression(
    schema: &Value,
    definitions: &BTreeMap<String, &Value>,
    indent: usize,
) -> Result<String, String> {
    if schema == &Value::Bool(true) || schema == &Value::Object(Map::new()) {
        return Ok("unknown".to_string());
    }
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        let name = reference
            .rsplit('/')
            .next()
            .ok_or_else(|| format!("Invalid schema reference: {reference}"))?;
        return Ok(escape_identifier(name));
    }
    if let Some(value) = schema.get("const") {
        return Ok(literal_type(value));
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        return Ok(values
            .iter()
            .map(literal_type)
            .collect::<Vec<_>>()
            .join(" | "));
    }
    if let Some(variants) = schema
        .get("anyOf")
        .or_else(|| schema.get("oneOf"))
        .and_then(Value::as_array)
    {
        let mut rendered = variants
            .iter()
            .map(|variant| type_expression(variant, definitions, indent))
            .collect::<Result<Vec<_>, _>>()?;
        rendered.sort();
        rendered.dedup();
        return Ok(rendered.join(" | "));
    }
    if let Some(types) = schema.get("type").and_then(Value::as_array) {
        let mut rendered = types
            .iter()
            .filter_map(Value::as_str)
            .map(|kind| primitive_type(kind, schema, definitions, indent))
            .collect::<Result<Vec<_>, _>>()?;
        rendered.sort();
        rendered.dedup();
        return Ok(rendered.join(" | "));
    }
    let kind = schema
        .get("type")
        .and_then(Value::as_str)
        .unwrap_or("object");
    primitive_type(kind, schema, definitions, indent)
}

fn primitive_type(
    kind: &str,
    schema: &Value,
    definitions: &BTreeMap<String, &Value>,
    indent: usize,
) -> Result<String, String> {
    if kind == "null" {
        return Ok("null".to_string());
    }
    if kind == "boolean" {
        return Ok("boolean".to_string());
    }
    if matches!(kind, "integer" | "number") {
        return Ok("number".to_string());
    }
    if kind == "string" {
        return Ok("string".to_string());
    }
    if kind == "array" {
        let item = schema.get("items").unwrap_or(&Value::Bool(true));
        return Ok(format!(
            "Array<{}>",
            type_expression(item, definitions, indent)?
        ));
    }
    if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
        let required = required_fields(schema);
        let mut output = String::from("{\n");
        for (property, property_schema) in properties {
            let optional = if required.contains(property) { "" } else { "?" };
            output.push_str(&format!(
                "{}  {property}{optional}: {};\n",
                spaces(indent),
                type_expression(property_schema, definitions, indent + 2)?
            ));
        }
        output.push_str(&format!("{}}}", spaces(indent)));
        return Ok(output);
    }
    if let Some(additional) = schema.get("additionalProperties") {
        if additional.as_bool() == Some(false) {
            return Ok("Record<string, never>".to_string());
        }
        return Ok(format!(
            "Record<string, {}>",
            type_expression(additional, definitions, indent)?
        ));
    }
    Ok("Record<string, unknown>".to_string())
}

fn literal_type(value: &Value) -> String {
    match value {
        Value::Null => "null".to_string(),
        Value::Bool(value) => value.to_string(),
        Value::Number(value) => value.to_string(),
        Value::String(value) => format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\"")),
        _ => "unknown".to_string(),
    }
}

fn escape_identifier(value: &str) -> String {
    if value
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_alphabetic() || character == '_')
        && value
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_')
    {
        value.to_string()
    } else {
        format!("\"{}\"", value.replace('"', "\\\""))
    }
}

fn doc_comment(schema: &Value, indent: usize) -> String {
    let Some(description) = schema.get("description").and_then(Value::as_str) else {
        return String::new();
    };
    let mut output = String::new();
    for line in description.lines() {
        output.push_str(&format!("{}/** {} */\n", spaces(indent), line.trim()));
    }
    output
}

fn spaces(count: usize) -> String {
    " ".repeat(count)
}
